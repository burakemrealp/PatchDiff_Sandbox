SYSTEM_PROMPT = """
You are a Challenger-tier League of Legends coach who communicates in clear, friendly, everyday player language accessible to players of every rank.
Your task is to evaluate 3 complete build variations (6 items total, or 7 for ADC with Role Quests + buy order + full rune page) generated by the combat simulator for:
PRACTICAL IN-GAME VIABILITY, SEASON 16 ROLE QUESTS, MAP RULES, AND ITEM-RUNE SYNERGY.

EVALUATION RULES:
1. Only cite items, runes, roles, map rules, and numbers provided in the input JSON; never invent items or statistics.
2. Always refer to the official player-facing patch version (e.g., 26.23).
3. TONE & CLARITY: Avoid academic or overly technical jargon ("EHP", "TTK", "metric optimization", "combined scaling"); instead use clear player terminology such as "full-combo damage", "damage per second (DPS)", "time to kill", "survivability", and "ability haste".
4. Catch items that score well mathematically in isolation but conflict with the champion's actual kit in real matches (e.g., Nashor's Tooth or Lich Bane on a long-range control mage); lower `practicality_score` and clearly explain why in `watchouts`.
5. Evaluate mana across items AND runes together: if the item build skips flat mana but the rune page picks Manaflow Band or Presence of Mind, explain how the rune covers the gap.
6. Remember Summoner's Rift Role Quests are inactive on ARAM; emphasize mana, sustain, and continuous teamfighting for ARAM.
7. For each variation, use `rune_item_synergy` to explain in 1-2 clear sentences why the chosen primary, secondary, and minor runes fit the item build.
8. Assign an explicit verdict: "RECOMMENDED", "SITUATIONAL", or "RISKY".
9. Return ONLY a valid raw JSON object matching the exact schema.
""".strip()


class VariationAIEvaluation(BaseModel):
    playstyle: str = Field(description="Variation playstyle key (burst, dps, balanced)")
    practicality_score: int = Field(ge=1, le=100, description="In-game practicality and viability score (1-100)")
    verdict: Literal["RECOMMENDED", "SITUATIONAL", "RISKY"]
    title: str = Field(description="Short concept title in the target language")
    rationale: str = Field(description="1-2 sentence explanation of why this variation shines or carries risk")
    rune_item_synergy: str = Field(
        default="",
        description="1-2 sentence explanation of synergy between the full rune page and the 6/7-item build",
    )
    strengths: List[str] = Field(default_factory=list, description="2-3 key strengths")
    watchouts: List[str] = Field(default_factory=list, description="1-2 situational caveats or watchouts")


class AIRecommendationReview(BaseModel):
    patch_summary: str = Field(description="1-2 sentence summary of how the patch affects champion, role/map, and build+rune choices")
    evaluations: List[VariationAIEvaluation] = Field(default_factory=list)


class AIBuildAdvisorService:
    """
    Evaluates complete 6/7-item + full rune page variations produced by MetaShiftAnalyzer
    using a two-layer architecture:
    Layer 1: OpenAI-Compatible LLM Analyst (Groq / OpenAI / DeepSeek)
    Layer 2: Deterministic LoL Domain Rule Engine (Offline Fallback - <5 ms)
    """

    @classmethod
    def evaluate_report(
        cls, report: Dict[str, Any], lang: str = "tr_TR"
    ) -> Tuple[Dict[str, Any], str, float]:
        start_time = time.perf_counter()
        riot_locale, bkey, llm_lang_name = normalize_locale(lang)
        variations = report.get("variations") or []
        if not variations:
            elapsed = round((time.perf_counter() - start_time) * 1000, 1)
            empty_msg = (
                "Değerlendirilecek varyasyon bulunamadı."
                if bkey == "tr"
                else "No variations found to evaluate."
            )
            return {**report, "ai_summary": empty_msg}, "empty", elapsed

        provider = settings.LLM_PROVIDER.lower().strip()
        review: AIRecommendationReview | None = None
        engine_used = "deterministic-advisor"

        # Layer 1: LLM Analyst
        if provider != "offline" and settings.LLM_API_KEY.strip():
            try:
                review = cls._call_llm_advisor(report, riot_locale=riot_locale, llm_lang_name=llm_lang_name)
                engine_used = f"{provider} ({settings.LLM_MODEL.strip()})"
            except Exception as exc:
                print(f"⚠️ AI Build Advisor LLM warning ({provider}): {exc}. Falling back to deterministic advisor.")
                review = None

        # Layer 2: Deterministic LoL Domain Fallback
        if review is None:
            review = cls._deterministic_review(report, lang=riot_locale)
            engine_used = "deterministic-advisor"

        enriched = cls._merge_and_rank(report, review, lang=riot_locale)
        elapsed = round((time.perf_counter() - start_time) * 1000, 1)
        return enriched, engine_used, elapsed

    @classmethod
    def _build_compact_brief(cls, report: Dict[str, Any]) -> Dict[str, Any]:
        from_disp = report.get("from_display_version") or to_display_version(report.get("from_version"))
        to_disp = report.get("to_display_version") or to_display_version(report.get("to_version"))
        gc = report.get("game_context") or {}

        compact_vars = []
        for v in report.get("variations", []):
            rp = v.get("rune_page") or {}
            pt = rp.get("primary_tree") or {}
            st = rp.get("secondary_tree") or {}
            compact_vars.append(
                {
                    "playstyle": v["playstyle"],
                    "item_count": len(v.get("items") or []),
                    "items_in_buy_order": [
                        {
                            "order": i.get("buy_order"),
                            "name": i["name"],
                            "slot": i.get("slot_type", "legendary"),
                            "gold": i["gold_total"],
                        }
                        for i in v["items"]
                    ],
                    "total_gold": v["total_gold"],
                    "rune_page": {
                        "primary": f"{pt.get('name', '')}: {(pt.get('keystone') or {}).get('name', v['keystone']['label'])} + {[r['name'] for r in pt.get('runes', [])]}",
                        "secondary": f"{st.get('name', '')}: {[r['name'] for r in st.get('runes', [])]}",
                        "shards": [s["label"] for s in rp.get("stat_shards", [])],
                        "synergy_notes": rp.get("synergy_notes", []),
                    },
                    "metrics": v["metrics"],
                    "patch_shift": v["patch_shift"],
                    "vs_old_meta": v["vs_old_meta"],
                }
            )

        return {
            "champion": report["champion_name"],
            "patch": f"{from_disp} -> {to_disp}",
            "role": gc.get("role_label", "Mid Lane"),
            "map": gc.get("map_label", "Summoner's Rift (5v5)"),
            "game_state": report.get("game_state", "even"),
            "total_slots": gc.get("total_item_slots", 6),
            "role_quest_reward": gc.get("quest_reward"),
            "target_profile": report["target_profile"],
            "tags": report.get("profile", {}).get("tags", []),
            "kit_archetype": report.get("profile", {}).get("kit_archetype_label"),
            "attack_range": report.get("profile", {}).get("attack_range"),
            "patch_adaptation_notes": (report.get("profile", {}).get("patch_signals") or {}).get(
                "adaptation_notes", []
            ),
            "uses_mana": report.get("profile", {}).get("uses_mana", True),
            "changed_in_patch": report.get("champion_changed_in_patch", False),
            "patch_diff_summary": (report.get("champion_patch_diff") or {}).get("summary"),
            "variations": compact_vars,
        }

    @classmethod
    def _call_llm_advisor(
        cls,
        report: Dict[str, Any],
        riot_locale: str = "tr_TR",
        llm_lang_name: str = "Turkish",
    ) -> AIRecommendationReview:
        compact_template = (
            f'{{"patch_summary":"1-2 sentence summary in {llm_lang_name}",'
            '"evaluations":[{"playstyle":"burst|dps|balanced","practicality_score":80,'
            f'"verdict":"RECOMMENDED|SITUATIONAL|RISKY","title":"Short title in {llm_lang_name}",'
            f'"rationale":"1-2 sentence player-friendly rationale in {llm_lang_name}",'
            f'"rune_item_synergy":"1-2 sentence item-rune synergy explanation in {llm_lang_name}",'
            f'"strengths":["... in {llm_lang_name}"],"watchouts":["... in {llm_lang_name}"]}}]}}'
        )
        lang_directive = (
            f"OUTPUT LANGUAGE REQUIREMENT: Write ALL human-readable fields "
            f"(patch_summary, title, rationale, rune_item_synergy, strengths, watchouts) "
            f"strictly in natural, friendly {llm_lang_name} ({riot_locale}) using authentic League of Legends player terminology. "
            f"Keep JSON keys and enum values (playstyle, verdict) exact."
        )
        brief_json = json.dumps(cls._build_compact_brief(report), ensure_ascii=False)
        url = f"{settings.LLM_BASE_URL.strip().rstrip('/')}/chat/completions"
        model_name = settings.LLM_MODEL.strip()

        headers = {
            "Authorization": f"Bearer {settings.LLM_API_KEY.strip()}",
            "Content-Type": "application/json",
        }
        body: Dict[str, Any] = {
            "model": model_name,
            "temperature": 0.0,
            "max_completion_tokens": 2400,
            "messages": [
                {
                    "role": "system",
                    "content": f"{SYSTEM_PROMPT}\n\n{lang_directive}\n\nExact JSON schema template:\n{compact_template}",
                },
                {
                    "role": "user",
                    "content": f"Analyze the following build & rune simulation report and return ONLY a valid JSON object written in {llm_lang_name}:\n{brief_json}",
                },
            ],
        }
        if "gpt-oss" in model_name.lower() or "o1" in model_name.lower() or "o3" in model_name.lower():
            body["reasoning_effort"] = "low"

        timeout_sec = max(14.0, float(settings.LLM_TIMEOUT_SECONDS))
        with httpx.Client(timeout=timeout_sec) as client:
            resp = client.post(url, headers=headers, json=body)
            resp.raise_for_status()
            raw_content = resp.json()["choices"][0]["message"].get("content") or ""
            start = raw_content.find("{")
            end = raw_content.rfind("}")
            if start == -1 or end == -1 or end <= start:
                raise ValueError("No valid JSON object found in LLM response.")
            return AIRecommendationReview.model_validate_json(raw_content[start : end + 1])

    @classmethod
    def _deterministic_review(cls, report: Dict[str, Any], lang: str = "tr_TR") -> AIRecommendationReview:
        _, bkey, _ = normalize_locale(lang)
        is_tr = bkey == "tr"
        profile = report.get("profile") or {}
        tags = set(profile.get("tags") or [])
        uses_mana = bool(profile.get("uses_mana", True))
        is_pure_mage = "Mage" in tags and not (tags & {"Fighter", "Marksman"})
        champ_name = report.get("champion_name", report.get("champion_key", "Champion"))
        changed = bool(report.get("champion_changed_in_patch", False))
        gc = report.get("game_context") or {}
        from_disp = report.get("from_display_version") or to_display_version(report.get("from_version"))
        to_disp = report.get("to_display_version") or to_display_version(report.get("to_version"))

        evaluations: List[VariationAIEvaluation] = []

        for var in report.get("variations", []):
            playstyle = var["playstyle"]
            items = var["items"]
            item_ids = {str(i["item_id"]) for i in items}
            metrics = var["metrics"]
            shift = var.get("patch_shift") or {}
            vs_meta = var.get("vs_old_meta") or {}
            rp = var.get("rune_page") or {}

            rune_keys = {
                r["key"]
                for r in (
                    (rp.get("primary_tree") or {}).get("runes", [])
                    + (rp.get("secondary_tree") or {}).get("runes", [])
                )
            }
            has_mana_rune = bool(rune_keys & {"ManaflowBand", "PresenceOfMind"})
            has_mana_item = any(float((i.get("stats") or {}).get("mana", 0.0)) >= 300.0 for i in items)

            score = 84
            strengths: List[str] = []
            watchouts: List[str] = []

            if is_pure_mage and "3115" in item_ids:
                score -= 22
                watchouts.append(
                    "Nashor'un Dişi sürekli düz vuruş menzili gerektirir; uzun menzilli büyücülerde risklidir."
                    if is_tr
                    else "Nashor's Tooth requires constant auto-attack range, which is risky on long-range mages."
                )
            elif is_pure_mage and "3100" in item_ids and "Assassin" not in tags:
                score -= 12
                watchouts.append(
                    "Lich Boğan pasifini tetiklemek için düz vuruş menziline girmek gerekir."
                    if is_tr
                    else "Triggering Lich Bane requires stepping into auto-attack range."
                )

            if is_pure_mage and uses_mana and not has_mana_item:
                if has_mana_rune:
                    score -= 2
                    strengths.append(
                        "Eşyalardaki mana açığı rün sayfasındaki mana rünüyle dengeleniyor."
                        if is_tr
                        else "Mana runes help compensate for the lack of a dedicated mana item."
                    )
                else:
                    score -= 8
                    watchouts.append(
                        "Dizilimde mana eşyası yok; uzun çatışmalarda mana yönetimi veya mavi güçlendirme gerekir."
                        if is_tr
                        else "No mana item included; careful mana management or Blue Buff is recommended."
                    )
            elif has_mana_item and uses_mana:
                score += 5
                strengths.append(
                    "Mana ekonomisi ve sürekli yetenek kullanımı dengeli."
                    if is_tr
                    else "Smooth mana economy for consistent spell casting."
                )

            gold_diff = int(vs_meta.get("gold_diff", 0))
            if gold_diff <= -300:
                score += 6
                strengths.append(
                    f"Eski meta dizilimine göre {abs(gold_diff)}g daha erken güç patlaması sağlar."
                    if is_tr
                    else f"Hits power spikes {abs(gold_diff)}g earlier than the previous patch build."
                )

            if metrics.get("ability_haste", 0) >= 35:
                score += 4
                strengths.append(
                    f"{metrics['ability_haste']} Yetenek Hızı ile çok sık yetenek rotasyonu sunar."
                    if is_tr
                    else f"{metrics['ability_haste']} Ability Haste enables rapid spell rotations."
                )

            if playstyle == "burst":
                title = "Tek Kombo & Hızlı Bitirici Dizilim" if is_tr else "Full Combo & Burst Build"
                strengths.append(
                    f"Seviye 18'de tek komboda {metrics['lvl18_burst']} hasar (yaklaşık {metrics['lvl18_ttk_sec']} sn öldürme süresi)."
                    if is_tr
                    else f"Deals {metrics['lvl18_burst']} full-combo damage at Level 18 (~{metrics['lvl18_ttk_sec']}s time to kill)."
                )
            elif playstyle == "dps":
                title = "Sürekli Hasar & Uzun Savaş Dizilimi" if is_tr else "Sustained DPS & Extended Fight Build"
                strengths.append(
                    f"Seviye 18'de saniyede {metrics['lvl18_dps']} sürekli hasar (DPS) üretir."
                    if is_tr
                    else f"Delivers {metrics['lvl18_dps']} sustained damage per second (DPS) at Level 18."
                )
            else:
                title = "Dengeli Tempo & Hayatta Kalma Dizilimi" if is_tr else "Balanced Tempo & Survivability Build"
                strengths.append(
                    f"Seviye 11'de {metrics['phys_ehp_lvl11']} fiziksel dayanıklılık ile savaşlarda daha uzun süre ayakta kalır."
                    if is_tr
                    else f"Provides {metrics['phys_ehp_lvl11']} physical durability at Level 11 for safer teamfights."
                )

            if shift.get("status") == "GAINED":
                score += 4
                strengths.append(
                    f"Yama {to_disp} ile güçlendi (Tek Kombo {shift.get('lvl18_burst_delta_pct', 0):+}%, Sürekli Hasar {shift.get('lvl18_dps_delta_pct', 0):+}%)."
                    if is_tr
                    else f"Buffed in Patch {to_disp} (Combo {shift.get('lvl18_burst_delta_pct', 0):+}%, DPS {shift.get('lvl18_dps_delta_pct', 0):+}%)."
                )
            elif shift.get("status") == "LOST":
                watchouts.append(
                    f"Yama {to_disp} zayıflatmasından etkilendi (Tek Kombo {shift.get('lvl18_burst_delta_pct', 0):+}%, Sürekli Hasar {shift.get('lvl18_dps_delta_pct', 0):+}%)."
                    if is_tr
                    else f"Affected by Patch {to_disp} nerfs (Combo {shift.get('lvl18_burst_delta_pct', 0):+}%, DPS {shift.get('lvl18_dps_delta_pct', 0):+}%)."
                )

            if not watchouts:
                watchouts.append(
                    "Rakip iyileştirme veya kitle kontrolüne göre son eşyada durumsal esneklik bırakılabilir."
                    if is_tr
                    else "Keep the final item slot flexible for Grievous Wounds or defensive utility as needed."
                )

            score = max(35, min(98, score))
            verdict: Literal["RECOMMENDED", "SITUATIONAL", "RISKY"] = (
                "RECOMMENDED" if score >= 78 else ("SITUATIONAL" if score >= 62 else "RISKY")
            )

            synergy_notes = rp.get("synergy_notes") or []
            if is_tr and synergy_notes:
                rune_synergy_text = " ".join(synergy_notes[:2])
            elif is_tr:
                rune_synergy_text = (
                    f"{var['keystone']['label']} anahtar rünü ve küçük rünler, "
                    f"{len(items)} eşyalık bu {gc.get('role_label', '')} diziliminin hasar ve oyun temposunu doğrudan destekler."
                )
            elif synergy_notes:
                rune_synergy_text = " ".join(synergy_notes[:2])
            else:
                rune_synergy_text = (
                    f"{var['keystone']['label']} and the stat shards directly reinforce the damage curve "
                    f"and tempo of this {len(items)}-item {gc.get('role_label', '')} build."
                )

            target_labels_tr = {"squishy": "kırılgan", "bruiser": "dövüşçü", "tank": "ağır tank"}
            target_tr = target_labels_tr.get(str(report.get("target_profile")), "standart")

            if is_tr:
                rationale = (
                    f"{champ_name} ({gc.get('role_label', 'Standart')} · {gc.get('map_label', 'Sihirdar Vadisi')}) için "
                    f"{len(items)} eşyalık ({var['total_gold']} Altın) bu dizilim ve {var['keystone']['label']} rün sayfası, "
                    f"{target_tr} rakiplere karşı Seviye 18'de tek komboda {metrics['lvl18_burst']} hasar ve saniyede {metrics['lvl18_dps']} sürekli hasar üretir."
                )
            else:
                rationale = (
                    f"For {champ_name} ({gc.get('role_label', '')} · {gc.get('map_label', 'SR')}), this {len(items)}-item build "
                    f"({var['total_gold']}g) paired with {var['keystone']['label']} delivers {metrics['lvl18_burst']} full-combo damage "
                    f"and {metrics['lvl18_dps']} DPS at Level 18 against {report.get('target_profile', 'squishy')} targets."
                )

            evaluations.append(
                VariationAIEvaluation(
                    playstyle=playstyle,
                    practicality_score=score,
                    verdict=verdict,
                    title=title,
                    rationale=rationale,
                    rune_item_synergy=rune_synergy_text,
                    strengths=strengths[:3],
                    watchouts=watchouts[:2],
                )
            )

        if is_tr:
            patch_summary = (
                f"Yama {from_disp} → {to_disp} ({gc.get('role_label', '')} · {gc.get('map_label', 'SR')}) kapsamında "
                f"{champ_name} doğrudan denge değişikliği aldı; {gc.get('total_item_slots', 6)} eşyalık tam dizilim ve "
                f"uyumlu tam rün sayfası buna göre optimize edildi."
                if changed
                else f"Yama {from_disp} → {to_disp} ({gc.get('role_label', '')} · {gc.get('map_label', 'SR')}) için "
                f"{champ_name} adına {gc.get('total_item_slots', 6)} eşyalık tam dizilimler ve eşyayla uyumlu rün sayfaları karşılaştırıldı."
            )
        else:
            patch_summary = (
                f"In Patch {from_disp} → {to_disp} ({gc.get('role_label', '')} · {gc.get('map_label', 'SR')}), "
                f"{champ_name} received direct balance changes; full {gc.get('total_item_slots', 6)}-item builds and "
                f"matching rune pages have been adapted accordingly."
                if changed
                else f"Full {gc.get('total_item_slots', 6)}-item builds and synchronized rune pages for {champ_name} "
                f"({gc.get('role_label', '')} · {gc.get('map_label', 'SR')}) were evaluated for Patch {from_disp} → {to_disp}."
            )
        return AIRecommendationReview(patch_summary=patch_summary, evaluations=evaluations)

    @classmethod
    def _merge_and_rank(
        cls, report: Dict[str, Any], review: AIRecommendationReview, lang: str = "tr_TR"
    ) -> Dict[str, Any]:
        eval_by_style = {e.playstyle.lower(): e for e in review.evaluations}
        fallback_review = cls._deterministic_review(report, lang=lang)
        fallback_by_style = {e.playstyle.lower(): e for e in fallback_review.evaluations}

        verdict_priority = {"RECOMMENDED": 3, "SITUATIONAL": 2, "RISKY": 1}

        merged_variations: List[Dict[str, Any]] = []
        for var in report.get("variations", []):
            style = str(var["playstyle"]).lower()
            ev = eval_by_style.get(style) or fallback_by_style.get(style)
            fb_ev = fallback_by_style.get(style)
            if ev:
                ev_dict = ev.model_dump()
                if not ev_dict.get("rune_item_synergy") and fb_ev:
                    ev_dict["rune_item_synergy"] = fb_ev.rune_item_synergy
            else:
                ev_dict = None
            merged_variations.append({**var, "ai_review": ev_dict})

        merged_variations.sort(
            key=lambda v: (
                verdict_priority.get((v.get("ai_review") or {}).get("verdict", "SITUATIONAL"), 0),
                int((v.get("ai_review") or {}).get("practicality_score", 0)),
                float(v.get("score", 0.0)),
            ),
            reverse=True,
        )

        for idx, v in enumerate(merged_variations, start=1):
            v["rank"] = idx

        return {
            **report,
            "ai_summary": review.patch_summary,
            "variations": merged_variations,
        }
